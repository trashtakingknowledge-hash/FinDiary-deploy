-- Zorvyn finance dashboard schema for Supabase PostgreSQL.
-- Run in Supabase Dashboard -> SQL Editor -> New query.
-- Preserves the application's custom users/password_hash table; this is not Supabase Auth.

CREATE TABLE IF NOT EXISTS public.users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    role VARCHAR(10) NOT NULL DEFAULT 'VIEWER' CHECK (role IN ('ADMIN', 'VIEWER')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    kind VARCHAR(10) NOT NULL CHECK (kind IN ('INCOME', 'EXPENSE', 'BOTH')),
    color VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS public.transactions (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id),
    category_id BIGINT REFERENCES public.categories(category_id),
    txn_type VARCHAR(10) NOT NULL CHECK (txn_type IN ('INCOME', 'EXPENSE')),
    amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    currency_code CHAR(3) NOT NULL DEFAULT 'INR',
    description VARCHAR(500),
    txn_date DATE NOT NULL DEFAULT CURRENT_DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_txn_user_date ON public.transactions(user_id, txn_date);
CREATE INDEX IF NOT EXISTS idx_txn_user_type ON public.transactions(user_id, txn_type);

CREATE TABLE IF NOT EXISTS public.bills (
    bill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id),
    name VARCHAR(200) NOT NULL,
    amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    currency_code CHAR(3) NOT NULL DEFAULT 'INR',
    due_date DATE NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'UNPAID' CHECK (status IN ('UNPAID', 'PAID')),
    category VARCHAR(100),
    notes VARCHAR(1000),
    recurrence VARCHAR(10) NOT NULL DEFAULT 'NONE' CHECK (recurrence IN ('NONE', 'WEEKLY', 'MONTHLY', 'YEARLY')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_bills_user_due ON public.bills(user_id, due_date, status);

CREATE TABLE IF NOT EXISTS public.goals (
    goal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id),
    name VARCHAR(200) NOT NULL,
    target_amount NUMERIC(14,2) NOT NULL CHECK (target_amount > 0),
    saved_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (saved_amount >= 0),
    currency_code CHAR(3) NOT NULL DEFAULT 'INR',
    deadline DATE,
    color VARCHAR(20),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.goal_contributions (
    contribution_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_id BIGINT NOT NULL REFERENCES public.goals(goal_id) ON DELETE CASCADE,
    amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    contribution_date DATE NOT NULL DEFAULT CURRENT_DATE,
    note VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS public.recurring_transactions (
    recurring_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id),
    category_id BIGINT REFERENCES public.categories(category_id),
    txn_type VARCHAR(10) NOT NULL CHECK (txn_type IN ('INCOME', 'EXPENSE')),
    amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    currency_code CHAR(3) NOT NULL DEFAULT 'INR',
    description VARCHAR(500),
    frequency VARCHAR(10) NOT NULL CHECK (frequency IN ('DAILY', 'WEEKLY', 'MONTHLY', 'YEARLY')),
    next_due_date DATE NOT NULL,
    is_active CHAR(1) NOT NULL DEFAULT 'Y' CHECK (is_active IN ('Y', 'N')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_rec_due ON public.recurring_transactions(is_active, next_due_date);

CREATE TABLE IF NOT EXISTS public.notifications (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id),
    title VARCHAR(200) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    notification_type VARCHAR(30) NOT NULL,
    is_read CHAR(1) NOT NULL DEFAULT 'N' CHECK (is_read IN ('Y', 'N')),
    is_dismissed CHAR(1) NOT NULL DEFAULT 'N' CHECK (is_dismissed IN ('Y', 'N')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_notif_user_created ON public.notifications(user_id, created_at);

